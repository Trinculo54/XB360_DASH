"""
Turn the boot animation's 17 shaders into HLSL that Direct3D 11 compiles.

The shaders are the title's own microcode, already translated to HLSL by
XenosRecomp (one file each, register for register). That output is written
for XenosRecomp's own runtime -- descriptor heaps, register spaces, Vulkan
attributes -- so this rewrites the plumbing around each body and leaves the
body alone:

  - the shared header goes, for a few lines that do the same job here (PRELUDE);
  - a sampler's descriptor indices become its stage number, which is what the
    header's packoffset for it encodes (c0.x.. for textures, c12.x.. for samplers);
  - the shared constants are two: the half-pixel offset that makes Direct3D 9
    rasterisation out of Direct3D 11's, and the alpha test's threshold.

Constant buffers: b0 vertex c0.., b1 pixel c0.., b2 the shared two. Textures
and samplers t0-t7 / s0-s7 by stage.

    python shaders.py <XenosRecomp hlsl dir> <out dir>

Writes shaderNN.vs.hlsl / shaderNN.ps.hlsl and, compiled with the Windows
SDK's fxc, the shaderNN.vs.cso / .ps.cso the app loads (src\\BootAnimation.cpp).
"""
import glob
import os
import re
import subprocess
import sys

PRELUDE = '''// Generated by tools/bootanim_extract/shaders.py from XenosRecomp's translation of the title's shader. Do not edit.
#define FLT_MIN asfloat(0xff7fffff)
#define FLT_MAX asfloat(0x7f7fffff)
#define select(c, a, b) ((c) ? (a) : (b))
#define SPEC_CONSTANT_ALPHA_TEST 2
#define g_SwappedTexcoords 0
#define g_Booleans 0
Texture2D<float4> g_tex[8] : register(t0);
SamplerState g_smp[8] : register(s0);
#define tfetch2D(t, s, uv, offset) g_tex[t].Sample(g_smp[s], uv)
#define tfetchTexcoord(swapped, value, index) (value)
#define tfetchR11G11B10(value) (value)
struct CubeMapData { float3 cubeMapDirections[2]; uint cubeMapIndex; };
'''


def convert(src):
    src = src.replace('\r', '')
    tail = src.split('#endif\n\n#endif\n', 1)[1]            # past the shared header
    # A sampler's stage, from where its descriptor indices sit.
    stage = {}
    for name, reg, comp in re.findall(r'uint (\w+)_Texture2DDescriptorIndex : packoffset\(c(\d+)\.([xyzw])\)', tail):
        stage[name] = int(reg) * 4 + 'xyzw'.index(comp)
    tail = re.sub(r'(?m)^\s*uint \w+DescriptorIndex : packoffset\(c\d+\.[xyzw]\);\n', '', tail)
    for name, n in stage.items():
        tail = tail.replace(f'{name}_Texture2DDescriptorIndex', str(n)).replace(f'{name}_SamplerDescriptorIndex', str(n))
    # A constant array is read through a macro of its own name that guards the index; fxc will not have
    # a macro and a variable share a name, and every index here is a literal in range: read it directly.
    for name in re.findall(r'(?m)^#define (\w+)\(INDEX\) .*\n', tail):
        tail = re.sub(r'(?m)^#define %s\(INDEX\) .*\n' % name, '', tail)
        tail = re.sub(r'\b%s\(([^()]+)\)' % name, r'%s[\1]' % name, tail)
    assert all(off == 'float2(0, 0)' for off in re.findall(r'tfetch2D\([^;]*?, (float2\([^)]*\))\)', tail)), \
        'a texture fetch with an offset: PRELUDE drops offsets'
    out = []
    spirv = 0                                               # inside an "#ifdef __spirv__" half
    for line in tail.split('\n'):
        s = line.strip()
        if s == '#ifdef __spirv__':
            spirv = 1
            continue
        if s == '#ifndef __spirv__':
            spirv = 3                                       # nothing but [shader(...)] lives in these
            continue
        if spirv and s == '#else':
            spirv = 2
            continue
        if spirv and s == '#endif':
            spirv = 0
            continue
        if spirv in (1, 3) or 'DescriptorIndex : packoffset' in s or s.startswith('[shader('):
            continue
        line = re.sub(r'\[\[vk::[^\]]*\]\]\s*', '', line).replace(', space4)', ')')
        # (fxc takes no macro with an empty argument list, so these two are written out)
        line = line.replace('g_SpecConstants()', '2').replace(
            'DEFINE_SHARED_CONSTANTS();', 'float2 g_HalfPixelOffset : packoffset(c0.x); float g_AlphaThreshold : packoffset(c0.z);')
        line = line.replace('in uint iFace', 'in bool iFace')
        line = re.sub(r'in uint4 (i\w+)', r'in float4 \1', line)
        out.append(line)
    return PRELUDE + '\n'.join(out) + '\n', stage


def main():
    src_dir, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    fxc = next(iter(sorted(glob.glob(r'C:\Program Files (x86)\Windows Kits\10\bin\*\x64\fxc.exe'), reverse=True)), None)
    for path in sorted(glob.glob(os.path.join(src_dir, 'Shader*.hlsl'))):
        number, kind = re.match(r'Shader(\d+)_(vertex|pixel)', os.path.basename(path)).groups()
        text, stage = convert(open(path, encoding='utf-8', errors='replace').read())
        name = f'shader{number}.{"vs" if kind == "vertex" else "ps"}.hlsl'
        with open(os.path.join(out_dir, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        note = 'not compiled: no fxc.exe found in the Windows SDK'
        if fxc:
            cso = os.path.join(out_dir, name[:-5] + '.cso')         # what the app loads
            r = subprocess.run([fxc, '/nologo', '/O3', '/T', 'vs_5_0' if kind == 'vertex' else 'ps_5_0', '/E', 'main',
                                '/Fo', cso, os.path.join(out_dir, name)], capture_output=True, text=True)
            note = 'compiled' if r.returncode == 0 else 'FAILS: ' + (r.stderr or r.stdout).strip().split('\n')[0][:200]
        print(f'{name}: samplers {stage or "none"}  {note}')


if __name__ == '__main__':
    main()
